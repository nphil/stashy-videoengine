#!/usr/bin/env bash
# ===========================================================================
# gen-package-swift.sh [tag]
# gen-package-swift.sh --pinned-tag   prints the release Package.swift pins
#
# Emits Package.swift (to stdout). Products:
#   FFmpeg       the six xcframeworks + FFmpegSupport (linker settings)
#   VideoEngine  VideoEngine + LoopbackHLS, once both Sources/ dirs exist
# Swift and test targets are emitted only for directories that exist, so the
# manifest follows the tree.
#
# Binaries:
#   default               release assets of BINARIES_TAG; that defaults to
#                         <tag>, else to the release the committed
#                         Package.swift downloads from
#   LOCAL_XCFRAMEWORKS=1  build/xcframeworks from a fresh build-ffmpeg.sh run
# Checksums: CHECKSUMS if set; build/dist/checksums.txt when BINARIES_TAG is
# the <tag> being released from a fresh build; otherwise the checksums.txt
# asset of the binaries release.
# ===========================================================================
set -euo pipefail

TAG="${1:-}"
REPO="${REPO:-nphil/videoengine}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LOCAL="${LOCAL_XCFRAMEWORKS:-0}"

# SwiftPM target name -> xcframework basename lib<name>
LIBS=(avutil avcodec avformat avfilter swscale swresample)

# Reads the committed manifest: `gen-package-swift.sh > Package.swift` empties
# the working copy before this script starts.
pinned_tag() {
  local manifest m
  manifest="$(git -C "$ROOT" show HEAD:Package.swift 2>/dev/null || cat "$ROOT/Package.swift")"
  m="$(grep -m 1 -o 'releases/download/[^/]*/' <<< "$manifest")" \
    || { echo "Package.swift pins no release; pass a tag or BINARIES_TAG" >&2; exit 1; }
  m="${m#releases/download/}"
  printf '%s\n' "${m%/}"
}

if [ "$TAG" = "--pinned-tag" ]; then
  pinned_tag
  exit 0
fi

if [ "$LOCAL" = "1" ]; then
  SOURCE_NOTE="build/xcframeworks"
else
  if [ -z "${BINARIES_TAG:-}" ]; then
    if [ -n "$TAG" ]; then BINARIES_TAG="$TAG"; else BINARIES_TAG="$(pinned_tag)"; fi
  fi
  SOURCE_NOTE="release $BINARIES_TAG"
  if [ -n "${CHECKSUMS:-}" ]; then
    CHK="$CHECKSUMS"
  elif [ "$BINARIES_TAG" = "$TAG" ]; then
    CHK="$ROOT/build/dist/checksums.txt"
  else
    CHK="$(mktemp)"
    trap 'rm -f "$CHK"' EXIT
    curl -fsSL --retry 3 --retry-delay 2 -o "$CHK" \
      "https://github.com/$REPO/releases/download/$BINARIES_TAG/checksums.txt"
  fi
  [ -s "$CHK" ] || { echo "no checksums at $CHK" >&2; exit 1; }
fi

has() { [ -d "$ROOT/$1" ]; }

emit_binary_target() {
  local name="$1" sum
  if [ "$LOCAL" = "1" ]; then
    has "build/xcframeworks/lib$name.xcframework" \
      || { echo "missing build/xcframeworks/lib$name.xcframework" >&2; exit 1; }
    cat <<EOF
        .binaryTarget(
            name: "$name",
            path: "build/xcframeworks/lib$name.xcframework"
        ),
EOF
  else
    sum="$(awk -v f="lib$name.xcframework.zip" '$2==f {print $1}' "$CHK")"
    [ -n "$sum" ] || { echo "missing checksum for lib$name" >&2; exit 1; }
    cat <<EOF
        .binaryTarget(
            name: "$name",
            url: "https://github.com/$REPO/releases/download/$BINARIES_TAG/lib$name.xcframework.zip",
            checksum: "$sum"
        ),
EOF
  fi
}

cat <<EOF
// swift-tools-version:6.2
// Generated by scripts/gen-package-swift.sh; binaries: $SOURCE_NOTE.
// Edit the generator, not this file.
//
// Consumers import the individual modules (Libavformat, Libavcodec, Libavutil,
// Libavfilter, Libswscale, Libswresample). The clang module map lives inside
// the libavutil xcframework and declares all six modules.
import PackageDescription

let package = Package(
    name: "VideoEngine",
    platforms: [.iOS(.v26)],
    products: [
        .library(
            name: "FFmpeg",
            targets: [
                "avutil", "avcodec", "avformat",
                "avfilter", "swscale", "swresample",
                "FFmpegSupport",
            ]
        ),
EOF
if has Sources/LoopbackHLS && has Sources/VideoEngine; then
  cat <<'EOF'
        .library(name: "VideoEngine", targets: ["VideoEngine", "LoopbackHLS"]),
EOF
fi
cat <<'EOF'
    ],
    targets: [
EOF
for name in "${LIBS[@]}"; do
  emit_binary_target "$name"
done
cat <<'EOF'
        .target(
            name: "FFmpegSupport",
            dependencies: [
                "avutil", "avcodec", "avformat",
                "avfilter", "swscale", "swresample",
            ],
            linkerSettings: [
                .linkedLibrary("z"),
                .linkedLibrary("bz2"),
                .linkedLibrary("iconv"),
                .linkedLibrary("c++"),
                .linkedFramework("VideoToolbox"),
                .linkedFramework("CoreMedia"),
                .linkedFramework("CoreVideo"),
                .linkedFramework("CoreFoundation"),
                .linkedFramework("AudioToolbox"),
                .linkedFramework("Metal"),
            ]
        ),
EOF
if has Sources/LoopbackHLS; then
  cat <<'EOF'
        .target(name: "LoopbackHLS"),
EOF
fi
if has Sources/VideoEngine; then
  cat <<'EOF'
        .target(
            name: "VideoEngine",
            dependencies: [
                "LoopbackHLS", "FFmpegSupport",
                "avutil", "avcodec", "avformat",
                "avfilter", "swscale", "swresample",
            ]
        ),
EOF
fi
if has Tests/LoopbackHLSTests; then
  cat <<'EOF'
        .testTarget(name: "LoopbackHLSTests", dependencies: ["LoopbackHLS"]),
EOF
fi
if has Tests/VideoEngineTests; then
  if has Tests/VideoEngineTests/Fixtures; then
    cat <<'EOF'
        .testTarget(
            name: "VideoEngineTests",
            dependencies: ["VideoEngine"],
            resources: [.copy("Fixtures")]
        ),
EOF
  else
    cat <<'EOF'
        .testTarget(name: "VideoEngineTests", dependencies: ["VideoEngine"]),
EOF
  fi
fi
cat <<'EOF'
    ]
)
EOF
